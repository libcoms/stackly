#!/usr/bin/env python3
"""Генератор задач ЕГЭ-2027 по профильной математике, №10 (прикладная задача по формуле), для банка stackly.

    python3 tools/gen_math10.py > /tmp/m10.json      # 36 задач повышенного уровня

Как в демоверсии и банке ФИПИ: формула из физики дана в условии, нужно выразить и найти величину. Торможение
и разгон автомобиля, высота подброшенного мяча (сколько секунд выше заданной отметки), распад изотопа, линза,
маятник, мощность тока, нагреватель, водолазный колокол, эффект Доплера. Числа подбираются под конечную
десятичную дробь. В описании <!--spec:…--> — проверка на Python («check»): tests/test_bank_math.py подставляет
в неё ответ x.
"""
import random, sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mathkit import F, ans, n, item, emit, is_dec

SEED = 20270110
TOPIC = 'Прикладная задача по формуле'
KINDS = ['brake', 'accel', 'ball', 'decay', 'lens', 'pendulum', 'power', 'heater', 'doppler', 'bell', 'stone', 'rope']
PLAN = [('П', k) for k in KINDS for _ in range(3)]


def make(rng, kind):
    if kind == 'brake':
        v0 = rng.choice([10, 12, 15, 18, 20, 24, 25, 30])
        a = rng.choice([2, 3, 4, 5, 6])
        t = F(rng.randint(1, 30), 2)
        if a * t >= v0:
            return None
        S = v0 * t - a * t * t / 2
        if not is_dec(S):
            return None
        text = (f'Автомобиль, движущийся со скоростью $v_{{0}} = {v0}$ м/с, начал торможение с постоянным ускорением '
                f'$a = {a}$ м/с². За $t$ секунд после начала торможения он прошёл путь $S = v_{{0}}t - \\frac{{at^{{2}}}}{{2}}$ (м). '
                f'Определите время, прошедшее с момента начала торможения, если известно, что за это время автомобиль '
                f'проехал ${n(S)}$ метров. Ответ дайте в секундах.')
        sol = (f'${n(S)} = {v0}t - {n(F(a, 2))}t^{{2}}$. Корни квадратного уравнения: ${n(t)}$ и ${n(F(2 * v0, a) - t)}$. '
               f'Автомобиль останавливается через $\\frac{{v_{{0}}}}{{a}} = {n(F(v0, a))}$ с, поэтому подходит меньший корень: ${n(t)}$.')
        return f'{v0}*x - {a}*x**2/2 == {S} and 0 < x < {F(v0, a)}', t, text, sol, f'Торможение: v₀ = {v0}, a = {a}, S = {n(S)}'
    if kind == 'accel':
        l = F(rng.randint(1, 20), 10)
        a = rng.choice([5000, 6000, 8000, 9000, 10000, 12000, 15000, 16000, 20000, 24000])
        v2 = 2 * l * a
        if math.isqrt(int(v2)) ** 2 != v2:
            return None
        v = math.isqrt(int(v2))
        text = (f'Автомобиль разгоняется на прямолинейном участке шоссе с постоянным ускорением $a$ (в км/ч²). '
                f'Скорость $v$ (в км/ч) вычисляется по формуле $v = \\sqrt{{2la}}$, где $l$ — пройденный автомобилем путь (в км). '
                f'Найдите ускорение, с которым должен двигаться автомобиль, чтобы, проехав ${n(l)}$ км, развить скорость ${v}$ км/ч. '
                f'Ответ дайте в км/ч².')
        sol = f'$v^{{2}} = 2la$, откуда $a = \\frac{{v^{{2}}}}{{2l}} = \\frac{{{v * v}}}{{2 \\cdot {n(l)}}} = {a}$.'
        return f'abs((2*{float(l)}*x)**0.5 - {v}) < 1e-9', F(a), text, sol, f'Разгон: l = {n(l)}, v = {v}'
    if kind == 'ball':
        h0 = F(rng.randint(1, 30), 10)
        t1, t2 = sorted(rng.sample([F(k, 10) for k in range(2, 30)], 2))
        # h(t) = h0 + v0 t − 5t², уровень H достигается в t1 и t2: −5(t − t1)(t − t2) + H
        v0 = 5 * (t1 + t2)
        H = h0 + 5 * t1 * t2
        if not is_dec(v0) or not is_dec(H):
            return None
        text = (f'Высота над землёй подброшенного вверх мяча меняется по закону $h(t) = {n(h0)} + {n(v0)}t - 5t^{{2}}$, где $h$ — '
                f'высота в метрах, $t$ — время в секундах, прошедшее с момента броска. Сколько секунд мяч будет находиться на '
                f'высоте не менее ${n(H)}$ метров?')
        sol = (f'${n(h0)} + {n(v0)}t - 5t^{{2}} \\ge {n(H)}$, то есть $5t^{{2}} - {n(v0)}t + {n(H - h0)} \\le 0$. Корни: '
               f'${n(t1)}$ и ${n(t2)}$, мяч выше отметки между ними: ${n(t2)} - {n(t1)} = {n(t2 - t1)}$ с.')
        return (f'abs(x - (({float(v0)}**2 - 20*{float(H - h0)})**0.5)/5) < 1e-9', t2 - t1, text, sol,
                f'Мяч: h₀ = {n(h0)}, v₀ = {n(v0)}, H = {n(H)}')
    if kind == 'decay':
        T = rng.choice([2, 3, 4, 5, 6, 8, 10, 12, 15, 20])
        m0 = rng.choice([16, 32, 40, 64, 80, 96, 120, 128, 160, 200, 256, 320, 640])
        k = rng.randint(1, 5)
        m = F(m0, 2 ** k)
        if not is_dec(m):
            return None
        text = (f'В ходе распада радиоактивного изотопа его масса $m$ (в мг) уменьшается по закону $m = m_{{0}} \\cdot 2^{{-\\frac{{t}}{{T}}}}$, '
                f'где $m_{{0}}$ — начальная масса изотопа, $t$ — время (в минутах), прошедшее от начального момента, $T$ — период '
                f'полураспада (в минутах). В начальный момент масса изотопа ${m0}$ мг. Период его полураспада ${T}$ мин. '
                f'Через сколько минут масса изотопа будет равна ${n(m)}$ мг?')
        sol = f'$2^{{-\\frac{{t}}{{{T}}}}} = \\frac{{{n(m)}}}{{{m0}}} = 2^{{-{k}}}$, значит, $\\frac{{t}}{{{T}}} = {k}$ и $t = {k * T}$ мин.'
        return f'abs({m0}*2**(-x/{T}) - {float(m)}) < 1e-9', F(k * T), text, sol, f'Изотоп: m₀ = {m0}, T = {T}, m = {n(m)}'
    if kind == 'lens':
        f = rng.choice([20, 25, 30, 36, 40, 45, 50, 60])
        d1 = rng.randint(f + 5, 4 * f)
        d2 = F(d1 * f, d1 - f)
        if not is_dec(d2) or d2 > 400:
            return None
        text = (f'Для получения на экране увеличенного изображения лампочки в лаборатории используется собирающая линза с главным '
                f'фокусным расстоянием $f = {f}$ см. Расстояние $d_{{1}}$ от линзы до лампочки и расстояние $d_{{2}}$ от линзы до экрана '
                f'связаны соотношением $\\frac{{1}}{{d_{{1}}}} + \\frac{{1}}{{d_{{2}}}} = \\frac{{1}}{{f}}$. Лампочку поставили на расстоянии '
                f'${d1}$ см от линзы. На каком расстоянии от линзы нужно поставить экран, чтобы изображение было чётким? Ответ дайте в сантиметрах.')
        sol = (f'$\\frac{{1}}{{d_{{2}}}} = \\frac{{1}}{{{f}}} - \\frac{{1}}{{{d1}}} = \\frac{{{d1 - f}}}{{{f * d1}}}$, '
               f'$d_{{2}} = \\frac{{{f * d1}}}{{{d1 - f}}} = {n(d2)}$ см.')
        return f'abs(1/{d1} + 1/x - 1/{f}) < 1e-12', d2, text, sol, f'Линза: f = {f}, d₁ = {d1}'
    if kind == 'pendulum':
        T = F(rng.randint(2, 40), 5)
        l = T * T / 4
        if not is_dec(l):
            return None
        text = (f'Период колебания математического маятника $T$ (в секундах) приближённо можно вычислить по формуле '
                f'$T = 2\\sqrt{{l}}$, где $l$ — длина нити (в метрах). Найдите длину нити маятника, период колебаний которого '
                f'составляет ${n(T)}$ с. Ответ дайте в метрах.')
        sol = f'$\\sqrt{{l}} = \\frac{{T}}{{2}} = {n(T / 2)}$, $l = {n(T / 2)}^{{2}} = {n(l)}$ м.'
        return f'abs(2*x**0.5 - {float(T)}) < 1e-9', l, text, sol, f'Маятник: T = {n(T)}'
    if kind == 'power':
        R = rng.choice([2, 4, 5, 8, 10, 12, 20, 25, 40, 50])
        I = F(rng.randint(2, 40), 2)
        P = I * I * R
        if not is_dec(P):
            return None
        text = (f'Мощность постоянного тока (в ваттах) вычисляется по формуле $P = I^{{2}}R$, где $I$ — сила тока (в амперах), '
                f'$R$ — сопротивление (в омах). Пользуясь этой формулой, найдите силу тока $I$, если мощность составляет '
                f'${n(P)}$ Вт, а сопротивление равно ${R}$ Ом. Ответ дайте в амперах.')
        sol = f'$I^{{2}} = \\frac{{P}}{{R}} = \\frac{{{n(P)}}}{{{R}}} = {n(P / R)}$, $I = {n(I)}$ А.'
        return f'abs(x*x*{R} - {float(P)}) < 1e-9 and x > 0', I, text, sol, f'Мощность: P = {n(P)}, R = {R}'
    if kind == 'heater':
        # T(t) = T0 + bt + at², a < 0; прибор отключают, когда температура достигает Tmax; найти время
        T0 = rng.choice([1200, 1300, 1400, 1450, 1500])
        tmax, tother = sorted(rng.sample(range(2, 30), 2))
        a = -rng.choice([10, 20, 25, 40, 50])
        b = -a * (tmax + tother)
        Tm = T0 + b * tmax + a * tmax * tmax
        text = (f'Для нагревательного элемента некоторого прибора экспериментально была получена зависимость температуры '
                f'(в кельвинах) от времени работы: $T(t) = T_{{0}} + bt + at^{{2}}$, где $t$ — время в минутах, $T_{{0}} = {T0}$ К, '
                f'$a = {a}$ К/мин², $b = {b}$ К/мин. Известно, что при температуре нагревателя свыше ${Tm}$ К прибор может '
                f'испортиться, поэтому его нужно отключить. Определите, через какое наибольшее время после начала работы нужно '
                f'отключить прибор. Ответ выразите в минутах.')
        sol = (f'${T0} + {b}t {a}t^{{2}} = {Tm}$, то есть ${-a}t^{{2}} - {b}t + {Tm - T0} = 0$, корни ${tmax}$ и ${tother}$. '
               f'Температура растёт и впервые достигает ${Tm}$ К при $t = {tmax}$ мин — тогда и отключают.')
        return f'{T0} + {b}*x + ({a})*x*x == {Tm} and x < {tother}', F(tmax), text, sol, f'Нагреватель: T₀ = {T0}, a = {a}, b = {b}'
    if kind == 'doppler':
        c = rng.choice([300, 315, 320, 330, 340])
        f0 = rng.choice([100, 120, 140, 150, 160, 180, 200])
        v = rng.randint(2, 40)
        f = F(f0 * (c + v), c - v)
        if not is_dec(f) or f.denominator != 1:
            return None
        text = (f'Локатор батискафа, равномерно погружающегося вертикально вниз, испускает ультразвуковые импульсы частотой '
                f'${f0}$ МГц. Скорость погружения батискафа (в м/с) вычисляется по формуле $v = c \\cdot \\frac{{f - f_{{0}}}}{{f + f_{{0}}}}$, '
                f'где $c = {c}$ м/с — скорость звука в воде, $f_{{0}}$ — частота испускаемых импульсов (в МГц), $f$ — частота '
                f'отражённого от дна сигнала (в МГц), регистрируемая приёмником. Определите частоту отражённого сигнала, если '
                f'скорость погружения батискафа равна ${v}$ м/с. Ответ дайте в МГц.')
        sol = (f'${v} = {c} \\cdot \\frac{{f - {f0}}}{{f + {f0}}}$, откуда ${v}(f + {f0}) = {c}(f - {f0})$, '
               f'$f = \\frac{{{f0}({c} + {v})}}{{{c} - {v}}} = {n(f)}$ МГц.')
        return f'abs({c}*(x - {f0})/(x + {f0}) - {v}) < 1e-9', f, text, sol, f'Локатор: f₀ = {f0}, c = {c}, v = {v}'
    if kind == 'bell':
        al = F(rng.choice([7, 9, 10, 12, 14, 15]), 1)
        nu = rng.choice([2, 3, 4, 5, 6])
        T = rng.choice([280, 290, 300, 320])
        k = rng.randint(1, 4)
        V1 = rng.choice([8, 12, 16, 20, 24, 32, 40, 48])
        V2 = F(V1, 2 ** k)
        A = al * nu * T * k
        if not is_dec(V2):
            return None
        text = (f'Водолазный колокол, содержащий $\\nu = {nu}$ моля воздуха при давлении $p_{{1}}$ и объёме $V_{{1}} = {V1}$ л, медленно опускают '
                f'на дно водоёма. При этом происходит изотермическое сжатие воздуха до конечного объёма $V_{{2}}$. Работа, совершаемая '
                f'водой при сжатии воздуха, определяется выражением $A = \\alpha \\nu T \\log_{{2}} \\frac{{V_{{1}}}}{{V_{{2}}}}$, где '
                f'$\\alpha = {n(al)}$ — постоянная, $T = {T}$ К — температура воздуха. Найдите, какой объём $V_{{2}}$ (в литрах) станет '
                f'занимать воздух, если при сжатии газа была совершена работа ${n(A)}$ Дж.')
        sol = (f'$\\log_{{2}} \\frac{{V_{{1}}}}{{V_{{2}}}} = \\frac{{A}}{{\\alpha \\nu T}} = \\frac{{{n(A)}}}{{{n(al)} \\cdot {nu} \\cdot {T}}} = {k}$, '
               f'значит, $\\frac{{{V1}}}{{V_{{2}}}} = 2^{{{k}}}$ и $V_{{2}} = {n(V2)}$ л.')
        return f'abs({float(al)}*{nu}*{T}*math.log2({V1}/x) - {float(A)}) < 1e-6', V2, text, sol, f'Колокол: ν = {nu}, V₁ = {V1}, A = {n(A)}'
    if kind == 'stone':
        # камень падает: h = 5t², за какое время упадёт с высоты H
        t = F(rng.randint(2, 40), 4)
        H = 5 * t * t
        if not is_dec(H):
            return None
        text = (f'Камень бросили с крыши без начальной скорости. Расстояние (в метрах), которое он пролетает за $t$ секунд, '
                f'вычисляется по формуле $h = 5t^{{2}}$. За сколько секунд камень долетит до земли, если высота крыши ${n(H)}$ м?')
        sol = f'$5t^{{2}} = {n(H)}$, $t^{{2}} = {n(H / 5)}$, $t = {n(t)}$ с (время положительно).'
        return f'abs(5*x*x - {float(H)}) < 1e-9 and x > 0', t, text, sol, f'Камень: h = {n(H)}'
    # rope: расстояние до горизонта l = √(2Rh), R = 6400 км
    l = rng.choice([4, 6, 8, 12, 16, 20, 24, 32, 40, 48, 64, 80])
    h = F(l * l * 1000, 2 * 6400)
    if not is_dec(h):
        return None
    text = (f'Расстояние (в километрах) от наблюдателя, находящегося на небольшой высоте $h$ километров над землёй, до '
            f'наблюдаемой им линии горизонта вычисляется по формуле $l = \\sqrt{{2Rh}}$, где $R = 6400$ км — радиус Земли. '
            f'С какой высоты горизонт виден на расстоянии ${l}$ км? Ответ выразите в метрах.')
    sol = f'$h = \\frac{{l^{{2}}}}{{2R}} = \\frac{{{l * l}}}{{12800}}$ км $= {n(h)}$ м.'
    return f'abs((2*6400*x/1000)**0.5 - {l}) < 1e-9', h, text, sol, f'Горизонт: l = {l}'


def main():
    rng = random.Random(SEED)
    out, titles = [], set()
    for k, (level, kind) in enumerate(PLAN, 1):
        for _ in range(20000):
            r = make(rng, kind)
            if r is None:
                continue
            check, x, text, sol, title = r
            if title in titles or not is_dec(x) or x <= 0:
                continue
            titles.add(title)
            break
        else:
            raise SystemExit(f'№10, {kind}: не удалось подобрать задачу')
        out.append(item(10, k, level, TOPIC, title, text, sol, ans(x), {'kind': kind, 'check': check}))
    emit(out)


if __name__ == '__main__':
    main()
