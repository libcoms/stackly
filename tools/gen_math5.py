#!/usr/bin/env python3
"""Генератор задач ЕГЭ-2027 по профильной математике, №5 (сложение и умножение вероятностей, полная
вероятность), для банка stackly.

    python3 tools/gen_math5.py > /tmp/m5.json      # 36 задач: 24 повышенных, 12 высоких

Как в банке ФИПИ и демоверсии: стрелок и мишени, независимые лампы («хотя бы одна»), два автомата с кофе
(вероятность пересечения), система контроля качества (формула полной вероятности, в том числе условная
«батарейка забракована — какова вероятность, что она неисправна»), масса буханки в интервале, стрельба до
первого попадания. Описание <!--spec:…--> — вероятности элементарных событий; tests/test_bank_math.py
перебирает все исходы опыта и считает ответ заново.
"""
import random, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mathkit import F, ans, n, item, emit, is_dec, rnd, plural

SEED = 20270105
TOPIC = 'Сложение и умножение вероятностей'
PLAN = ([('П', 'shooter')] * 5 + [('П', 'lamps')] * 5 + [('П', 'coffee')] * 5 + [('П', 'bread')] * 4 + [('П', 'until')] * 5
        + [('В', 'control')] * 6 + [('В', 'bayes')] * 6)
NUMW = {2: 'двух', 3: 'трёх', 4: 'четырёх', 5: 'пяти'}
ACC = {2: 'две', 3: 'три', 4: 'четыре'}


def d(x):
    return n(x)


def make(rng, fam):
    if fam == 'shooter':
        m = rng.randint(3, 5)
        p = F(rng.choice([5, 6, 7, 8, 9]), 10)
        hits = rng.randint(1, m - 1)
        pat = [1] * hits + [0] * (m - hits)
        order = rng.choice(['first', 'last'])
        if order == 'last':
            pat = pat[::-1]
        res = p ** hits * (1 - p) ** (m - hits)
        what = (f'попадёт в {"первую" if order == "first" else "последнюю"} мишень' if hits == 1 else f'попадёт в {ACC[hits]} {"первые" if order == "first" else "последние"} мишени')
        rest = m - hits
        miss = 'не попадёт в остальные' if rest > 1 else f'не попадёт в {"последнюю" if order == "first" else "первую"}'
        text = (f'Стрелок стреляет по одному разу в каждую из {NUMW[m]} мишеней. Вероятность попадания в мишень при '
                f'каждом отдельном выстреле равна ${d(p)}$. Найдите вероятность того, что стрелок {what} и {miss}.')
        sol = (f'Выстрелы независимы: вероятности перемножаются. ${d(p)}^{{{hits}}} \\cdot {d(1 - p)}^{{{rest}}} = {d(res)}$.')
        return {'fam': fam, 'p': str(p), 'pat': pat}, res, text, sol, f'Стрелок: {m} {plural(m, "мишень", "мишени", "мишеней")}, попаданий {hits}, {"первые" if order == "first" else "последние"}, p = {d(p)}'
    if fam == 'lamps':
        m = rng.randint(2, 4)
        q = F(rng.choice([1, 2, 3, 4, 5]), 10) if m < 4 else F(rng.choice([1, 2, 3]), 10)
        res = 1 - q ** m
        text = (f'Помещение освещается {"двумя лампами" if m == 2 else NUMW[m] + " лампами"}. Вероятность перегорания каждой лампы '
                f'в течение года равна ${d(q)}$. Лампы перегорают независимо друг от друга. Найдите вероятность того, что в '
                f'течение года хотя бы одна лампа не перегорит.')
        sol = (f'Противоположное событие — перегорят все {m} лампы: ${d(q)}^{{{m}}} = {d(q ** m)}$. '
               f'Искомая вероятность $1 - {d(q ** m)} = {d(res)}$.')
        return {'fam': fam, 'q': str(q), 'm': m}, res, text, sol, f'Лампы: {m} шт., перегорание {d(q)}'
    if fam == 'coffee':
        a = F(rng.randint(2, 4), 10)
        c = F(rng.randint(3, int(a * 100) - 1), 100) if rng.random() < 0.5 else F(rng.randint(1, 9), 100)
        if c >= a or c < a * a * F(1, 2):
            return None
        ask = rng.choice(['both_stay', 'one_left'])
        res = 1 - (2 * a - c) if ask == 'both_stay' else 2 * a - 2 * c
        text = (f'В торговом центре два одинаковых автомата продают кофе. Вероятность того, что к концу дня в автомате '
                f'закончится кофе, равна ${d(a)}$. Вероятность того, что кофе закончится в обоих автоматах, равна ${d(c)}$. '
                + ('Найдите вероятность того, что к концу дня кофе останется в обоих автоматах.' if ask == 'both_stay'
                   else 'Найдите вероятность того, что к концу дня кофе закончится ровно в одном автомате.'))
        if ask == 'both_stay':
            sol = (f'Кофе закончится хотя бы в одном автомате с вероятностью $P(A \\cup B) = {d(a)} + {d(a)} - {d(c)} = {d(2 * a - c)}$. '
                   f'Противоположное событие: $1 - {d(2 * a - c)} = {d(res)}$.')
        else:
            sol = (f'Только в первом: ${d(a)} - {d(c)} = {d(a - c)}$, столько же только во втором. Ровно в одном: '
                   f'$2 \\cdot {d(a - c)} = {d(res)}$.')
        return {'fam': fam, 'a': str(a), 'c': str(c), 'ask': ask}, res, text, sol, f'Кофе: {d(a)} и {d(c)}, {"оба остались" if ask == "both_stay" else "ровно один"}'
    if fam == 'bread':
        lo, hi = rng.choice([(790, 810), (490, 510), (995, 1005), (1490, 1510)])
        a = F(rng.randint(80, 99), 100)
        b = F(rng.randint(80, 99), 100)
        res = a + b - 1
        if res <= 0:
            return None
        text = (f'При выпечке хлеба производится контрольное взвешивание свежей буханки. Известно, что вероятность того, '
                f'что масса окажется меньше {hi} г, равна ${d(a)}$. Вероятность того, что масса окажется больше {lo} г, '
                f'равна ${d(b)}$. Найдите вероятность того, что масса буханки больше {lo} г, но меньше {hi} г.')
        sol = (f'События «меньше {hi} г» и «больше {lo} г» вместе покрывают все исходы, а пересекаются ровно на нужном '
               f'интервале: $P = {d(a)} + {d(b)} - 1 = {d(res)}$.')
        return {'fam': fam, 'a': str(a), 'b': str(b)}, res, text, sol, f'Буханка {lo}–{hi} г: {d(a)} и {d(b)}'
    if fam == 'until':
        p = F(rng.choice([4, 5, 6, 7, 8, 9]), 10)
        k = rng.randint(2, 4)
        res = 1 - (1 - p) ** k
        text = (f'Стрелок в тире стреляет по мишени до тех пор, пока не поразит её. Вероятность попадания при каждом '
                f'выстреле равна ${d(p)}$. Найдите вероятность того, что стрелку потребуется не больше {k} выстрелов.')
        sol = (f'Противоположное событие — первые {k} выстрела мимо: ${d(1 - p)}^{{{k}}} = {d((1 - p) ** k)}$. '
               f'Искомая вероятность $1 - {d((1 - p) ** k)} = {d(res)}$.')
        return {'fam': fam, 'p': str(p), 'k': k}, res, text, sol, f'До попадания: p = {d(p)}, не больше {k}'
    # control / bayes: батарейка неисправна с вероятностью q; система бракует неисправную с вероятностью r1,
    # исправную по ошибке — с вероятностью r2
    q = F(rng.randint(1, 4), 100) * 5
    r1 = F(rng.choice([90, 92, 95, 96, 98, 99]), 100)
    r2 = F(rng.choice([1, 2, 3, 4, 5]), 100)
    tot = q * r1 + (1 - q) * r2
    text = (f'Автоматическая линия изготавливает батарейки. Вероятность того, что готовая батарейка неисправна, равна '
            f'${d(q)}$. Перед упаковкой каждая батарейка проходит систему контроля качества. Вероятность того, что система '
            f'забракует неисправную батарейку, равна ${d(r1)}$. Вероятность того, что система по ошибке забракует исправную '
            f'батарейку, равна ${d(r2)}$. ')
    if fam == 'control':
        text += 'Найдите вероятность того, что случайно выбранная изготовленная батарейка будет забракована системой контроля.'
        sol = (f'Забраковать могут неисправную или исправную батарейку: $P = {d(q)} \\cdot {d(r1)} + {d(1 - q)} \\cdot {d(r2)} '
               f'= {d(q * r1)} + {d((1 - q) * r2)} = {d(tot)}$.')
        return {'fam': fam, 'q': str(q), 'r1': str(r1), 'r2': str(r2)}, tot, text, sol, f'Контроль: брак {d(q)}, {d(r1)}, {d(r2)}'
    res = q * r1 / tot
    text += ('Батарейка оказалась забракованной. Найдите вероятность того, что она действительно неисправна. '
             'Результат округлите до сотых.')
    sol = (f'Вероятность забраковать: ${d(q)} \\cdot {d(r1)} + {d(1 - q)} \\cdot {d(r2)} = {d(tot)}$. Из неё на неисправные '
           f'приходится ${d(q * r1)}$, поэтому $P = \\frac{{{d(q * r1)}}}{{{d(tot)}}} \\approx {d(rnd(res))}$.')
    return {'fam': fam, 'q': str(q), 'r1': str(r1), 'r2': str(r2), 'round': 2}, rnd(res), text, sol, f'Забракована — неисправна: {d(q)}, {d(r1)}, {d(r2)}'


def main():
    rng = random.Random(SEED)
    out, titles = [], set()
    for k, (level, fam) in enumerate(PLAN, 1):
        for _ in range(5000):
            r = make(rng, fam)
            if r is None:
                continue
            sp, p, text, sol, title = r
            if title in titles or not is_dec(p) or not 0 < p < 1:
                continue
            titles.add(title)
            break
        else:
            raise SystemExit(f'№5, {fam}: не удалось подобрать задачу')
        out.append(item(5, k, level, TOPIC, title, text, sol, ans(p), sp))
    emit(out)


if __name__ == '__main__':
    main()
