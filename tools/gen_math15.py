#!/usr/bin/env python3
"""Генератор задач ЕГЭ-2027 по профильной математике, №15 (стереометрия: доказательство и вычисление, 3 балла).

    python3 tools/gen_math15.py > /tmp/m15.json      # 16 задач повышенного уровня

Пункт а — доказательство (оно верно при любых размерах фигуры и записано в эталонном решении), пункт б —
вычисление, размеры подобраны под конечную десятичную дробь. Правильная четырёхугольная пирамида (перпендикулярность
плоскостей, тангенс угла между гранью и основанием), куб (перпендикулярность диагонали и плоскости, расстояние
до плоскости), прямоугольный параллелепипед с квадратным основанием (перпендикулярность скрещивающихся прямых,
тангенс угла диагонали с основанием), правильная треугольная призма (перпендикуляр к грани, расстояние).
В описании <!--spec:…--> — размеры; tests/test_bank_math.py строит тело в координатах и считает ответ векторно.
"""
import random, sys, os, math
from fractions import Fraction as F
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mathkit import n, ans, item2, emit, is_dec

SEED = 20270115
TOPIC = 'Стереометрия: доказательство и вычисление'
KINDS = ['pyr', 'cube', 'box', 'prism']
PLAN = [('П', k) for k in KINDS for _ in range(4)]
S1 = '<sub>1</sub>'


def make(rng, kind):
    if kind == 'pyr':
        a = rng.choice([2, 4, 6, 8, 10, 12])
        h = rng.choice([1, 2, 3, 4, 5, 6, 7, 9])
        t = F(2 * h, a)
        if not is_dec(t):
            return None
        text = (f'В правильной четырёхугольной пирамиде $SABCD$ сторона основания $AB = {a}$, высота $SO = {h}$ ($O$ — центр основания).'
                f'<br>а) Докажите, что плоскость $SAC$ перпендикулярна плоскости $SBD$.'
                f'<br>б) Найдите тангенс угла между плоскостью $SCD$ и плоскостью основания.')
        sol = (f'<p><b>а)</b> Основание — квадрат, его диагонали перпендикулярны: $BD \\perp AC$. Высота $SO$ перпендикулярна плоскости '
               f'основания, поэтому $BD \\perp SO$. Прямая $BD$ перпендикулярна двум пересекающимся прямым $AC$ и $SO$ плоскости $SAC$, '
               f'значит, $BD \\perp (SAC)$. Плоскость $SBD$ проходит через перпендикуляр к плоскости $SAC$, поэтому плоскости перпендикулярны.</p>'
               f'<p><b>б)</b> Пусть $M$ — середина $CD$. $OM \\perp CD$ (средняя линия квадрата), $SM \\perp CD$ (медиана равнобедренного '
               f'треугольника $SCD$), поэтому $\\angle SMO$ — линейный угол двугранного угла между $SCD$ и основанием. '
               f'$OM = \\frac{{AB}}{{2}} = {n(F(a, 2))}$, $\\tg \\angle SMO = \\frac{{SO}}{{OM}} = \\frac{{{h}}}{{{n(F(a, 2))}}} = {n(t)}$.</p>')
        return {'kind': kind, 'a': a, 'h': h}, t, text, sol, f'Пирамида SABCD: AB = {a}, SO = {h}'
    if kind == 'cube':
        k = rng.randint(1, 6)
        text = (f'Дан куб $ABCDA_{{1}}B_{{1}}C_{{1}}D_{{1}}$ с ребром ${k}\\sqrt{{3}}$.'
                f'<br>а) Докажите, что прямая $A_{{1}}C$ перпендикулярна плоскости $BDC_{{1}}$.'
                f'<br>б) Найдите расстояние от точки $C$ до плоскости $BDC_{{1}}$.')
        sol = (f'<p><b>а)</b> $BD \\perp AC$ (диагонали квадрата) и $BD \\perp AA_{{1}}$, значит, $BD \\perp (AA_{{1}}C)$ и $BD \\perp A_{{1}}C$. '
               f'Аналогично $BC_{{1}} \\perp B_{{1}}C$ и $BC_{{1}} \\perp A_{{1}}B_{{1}}$, значит, $BC_{{1}} \\perp (A_{{1}}B_{{1}}C)$ и $BC_{{1}} \\perp A_{{1}}C$. '
               f'Прямая $A_{{1}}C$ перпендикулярна двум пересекающимся прямым $BD$ и $BC_{{1}}$ плоскости $BDC_{{1}}$, что и требовалось.</p>'
               f'<p><b>б)</b> Пирамида $CBDC_{{1}}$: её объём $V = \\frac{{1}}{{3}} \\cdot \\frac{{a^{{2}}}}{{2}} \\cdot a = \\frac{{a^{{3}}}}{{6}}$, '
               f'а грань $BDC_{{1}}$ — правильный треугольник со стороной $a\\sqrt{{2}}$ и площадью $\\frac{{\\sqrt{{3}}}}{{2}}a^{{2}}$. '
               f'Расстояние $d = \\frac{{3V}}{{S}} = \\frac{{a}}{{\\sqrt{{3}}}} = \\frac{{{k}\\sqrt{{3}}}}{{\\sqrt{{3}}}} = {k}$.</p>')
        return {'kind': kind, 'k': k}, F(k), text, sol, f'Куб с ребром {k}√3: расстояние до BDC₁'
    if kind == 'box':
        # основание задано диагональю (а не стороной), чтобы тангенс угла B₁D с основанием был рациональным
        dg = 2 * rng.choice([3, 4, 5, 6, 8, 12])
        c = rng.randint(1, 20)
        t = F(c, dg)
        if not is_dec(t):
            return None
        text = (f'В прямоугольном параллелепипеде $ABCDA_{{1}}B_{{1}}C_{{1}}D_{{1}}$ основание $ABCD$ — квадрат с диагональю ${dg}$, '
                f'боковое ребро $AA_{{1}} = {c}$.<br>а) Докажите, что прямые $AC$ и $B_{{1}}D$ перпендикулярны.'
                f'<br>б) Найдите тангенс угла между прямой $B_{{1}}D$ и плоскостью основания.')
        sol = (f'<p><b>а)</b> $AC \\perp BD$ (диагонали квадрата) и $AC \\perp BB_{{1}}$ (боковое ребро перпендикулярно основанию). '
               f'Значит, $AC$ перпендикулярна плоскости $BB_{{1}}D$, а с ней — и лежащей в ней прямой $B_{{1}}D$.</p>'
               f'<p><b>б)</b> $BD$ — проекция $B_{{1}}D$ на плоскость основания, искомый угол — $\\angle B_{{1}}DB$. '
               f'$\\tg \\angle B_{{1}}DB = \\frac{{BB_{{1}}}}{{BD}} = \\frac{{{c}}}{{{dg}}} = {n(t)}$.</p>')
        return {'kind': kind, 'dg': dg, 'c': c}, t, text, sol, f'Параллелепипед: диагональ основания {dg}, ребро {c}'
    k = rng.randint(1, 6)
    a_txt = f'{2 * k}\\sqrt{{3}}'
    text = (f'В правильной треугольной призме $ABCA_{{1}}B_{{1}}C_{{1}}$ все рёбра равны ${a_txt}$, $M$ — середина ребра $AB$.'
            f'<br>а) Докажите, что прямая $CM$ перпендикулярна плоскости $ABB_{{1}}$.'
            f'<br>б) Найдите расстояние от точки $C$ до плоскости $ABB_{{1}}$.')
    sol = (f'<p><b>а)</b> $CM$ — медиана правильного треугольника $ABC$, поэтому $CM \\perp AB$. Боковое ребро $AA_{{1}}$ перпендикулярно '
           f'основанию, значит, $AA_{{1}} \\perp CM$. Прямая $CM$ перпендикулярна двум пересекающимся прямым $AB$ и $AA_{{1}}$ плоскости '
           f'$ABB_{{1}}$, что и требовалось.</p><p><b>б)</b> По пункту а расстояние равно $CM$ — высоте правильного треугольника со '
           f'стороной ${a_txt}$: $CM = \\frac{{\\sqrt{{3}}}}{{2}} \\cdot {a_txt} = {3 * k}$.</p>')
    return {'kind': 'prism', 'k': k}, F(3 * k), text, sol, f'Правильная призма с ребром {2 * k}√3: расстояние от C до ABB₁'


def main():
    rng = random.Random(SEED)
    out, titles = [], set()
    for k, (level, kind) in enumerate(PLAN, 1):
        for _ in range(20000):
            r = make(rng, kind)
            if r is None:
                continue
            sp, x, text, sol, title = r
            if title in titles:
                continue
            titles.add(title)
            break
        else:
            raise SystemExit(f'№15, {kind}: не удалось подобрать задачу')
        out.append(item2(15, k, level, TOPIC, title, text, sol + f'<p>Ответ: б) ${n(x)}$.</p>', ans(x), sp, auto=True))
    emit(out)


if __name__ == '__main__':
    main()
